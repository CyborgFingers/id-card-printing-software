// Regenerates web/js/legal.js (the licence and supported-printers text built into the
// screens) and web/legal/THIRD-PARTY-NOTICES.txt from the files in legal/.
// Run after editing anything in legal/:   node tools/gen-legal.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(root, 'legal', f), 'utf8').replace(/\r\n/g, '\n');
const licence = read('LICENSE.txt');
const printers = read('SUPPORTED-PRINTERS.txt');
const m = /Licence version ([\d.]+)/.exec(licence);
if (!m) throw new Error('LICENSE.txt must contain "Licence version X.Y"');

const js = `// ID Card Printing Software Free - built-in legal texts.
// Copyright (c) 2026 Josh McNabb. All rights reserved.
// Generated by tools/gen-legal.mjs from legal/LICENSE.txt and legal/SUPPORTED-PRINTERS.txt; do not edit by hand.
export const LICENSE_VERSION = ${JSON.stringify(m[1])};
export const LICENSE_TEXT = ${JSON.stringify(licence)};
export const SUPPORTED_PRINTERS_TEXT = ${JSON.stringify(printers)};
`;
fs.writeFileSync(path.join(root, 'web/js/legal.js'), js);
fs.mkdirSync(path.join(root, 'web/legal'), { recursive: true });
fs.copyFileSync(path.join(root, 'legal/THIRD-PARTY-NOTICES.txt'), path.join(root, 'web/legal/THIRD-PARTY-NOTICES.txt'));

// The service's LicenseVersion must match, so everyone is asked to accept changed terms.
const service = fs.readFileSync(path.join(root, 'desktop/src/IdCard.Core/Service/AppService.cs'), 'utf8');
const sv = /LicenseVersion = "([^"]+)"/.exec(service);
if (!sv || sv[1] !== m[1]) console.warn(`WARNING: AppService.cs LicenseVersion is '${sv && sv[1]}' but LICENSE.txt says '${m[1]}'. Update it so users re-accept.`);
console.log(`legal.js written (licence version ${m[1]})`);
