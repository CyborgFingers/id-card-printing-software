// Regenerates web/js/help.js (the Help topics built into the screens) from docs/USER-GUIDE.md, the
// user guide shown on GitHub, so both always say the same thing. Each "## " section is one topic.
// Run after editing the guide:   node tools/gen-help.mjs
// The guide may use: ### headings, paragraphs, - and 1. lists (one level), > notes, | tables,
// **bold**, *italic*, `code` and [links](#other-topic). Images (screenshots) show on GitHub only.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GUIDE = path.join(root, 'docs/USER-GUIDE.md');
export const OUT = path.join(root, 'web/js/help.js');

// GitHub's heading anchors, so [links](#topic) work in both places.
export const slug = (s) => s.trim().toLowerCase().replace(/[^\p{L}\p{N}\s-]/gu, '').replace(/\s/g, '-');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function inline(s) {
  const code = [];
  s = esc(s.replace(/!\[[^\]]*\]\([^)]*\)/g, ''))
    .replace(/`([^`]+)`/g, (_, c) => `\u0000${code.push(c) - 1}\u0000`)
    .replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
    .replace(/(^|[^*\w])\*(?!\s)(.+?)\*(?!\w)/g, '$1<i>$2</i>')
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, t, href) => href.startsWith('#')
      ? `<a href="#/help/${href.slice(1)}">${t}</a>`
      : `<a href="${href}" target="_blank" rel="noopener">${t}</a>`);
  return s.replace(/\u0000(\d+)\u0000/g, (_, i) => `<code>${esc(code[+i])}</code>`);
}

const LIST = /^(\d+\.|-) /;
function blocks(lines) {
  const out = []; let i = 0;
  const take = (test) => { const got = []; while (i < lines.length && test(lines[i])) got.push(lines[i++]); return got; };
  while (i < lines.length) {
    const l = lines[i];
    if (!l.trim()) { i++; continue; }
    if (l.startsWith('### ')) { out.push(`<h3 id="${slug(l.slice(4))}">${inline(l.slice(4))}</h3>`); i++; continue; }
    if (l.startsWith('![')) { i++; continue; }   // a screenshot: GitHub only
    if (l.startsWith('>')) {
      const body = take(x => x.startsWith('>')).map(x => x.replace(/^>\s?/, '')).join(' ');
      out.push(`<div class="note">${inline(body)}</div>`); continue;
    }
    if (l.startsWith('|')) {
      const rows = take(x => x.startsWith('|')).filter(x => !/^\|[\s:|-]+\|$/.test(x)).map(x => x.replace(/^\||\|$/g, '').split('|').map(c => inline(c.trim())));
      out.push(`<table><thead><tr>${rows[0].map(c => `<th>${c}</th>`).join('')}</tr></thead><tbody>${rows.slice(1).map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}</tbody></table>`); continue;
    }
    const list = l.match(LIST);
    if (list) {
      const tag = list[1] === '-' ? 'ul' : 'ol', items = [];
      while (i < lines.length && (LIST.test(lines[i]) || (/^\s{2,}\S/.test(lines[i]) && items.length))) {
        if (/^\s/.test(lines[i])) items[items.length - 1] += ' ' + lines[i].trim(); else items.push(lines[i].replace(LIST, ''));
        i++;
      }
      out.push(`<${tag}>${items.map(t => `<li>${inline(t)}</li>`).join('')}</${tag}>`); continue;
    }
    out.push(`<p>${inline(take(x => x.trim() && !/^(#{2,3} |>|\||(\d+\.|-) |!\[)/.test(x)).join(' '))}</p>`);
  }
  return out.join('\n');
}

const plain = (html) => html.replace(/<\/?(b|i|code|a)\b[^>]*>/g, '').replace(/<[^>]+>/g, ' ').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

/** Topics from the guide's Markdown: [{ id, title, summary, html, text }]. "Contents" is GitHub's table of contents and is left out. */
export function buildTopics(md) {
  const topics = [];
  for (const sec of md.replace(/\r\n/g, '\n').split(/^## /m).slice(1)) {
    const [head, ...rest] = sec.split('\n');
    if (head.trim() === 'Contents') continue;
    const html = blocks(rest);
    const first = html.match(/^<p>(.*?)<\/p>/);   // the opening paragraph is the topic's summary in the Help list
    if (!first) throw new Error(`Topic "${head.trim()}" must start with a short summary paragraph`);
    topics.push({ id: slug(head), title: head.trim(), summary: plain(first[1]), html, text: plain(html) });
  }
  const ids = new Set(topics.map(t => t.id));
  for (const t of topics) for (const [, id] of t.html.matchAll(/href="#\/help\/([^"]+)"/g)) if (!ids.has(id)) throw new Error(`Topic "${t.title}" links to #${id}, which isn't a topic`);
  return topics;
}

export const render = (topics) => `// ID Card Printing Software Free - the Help topics built into the screens.
// Copyright (c) 2026 Josh McNabb. All rights reserved.
// Generated by tools/gen-help.mjs from docs/USER-GUIDE.md; do not edit by hand.
export const HELP_TOPICS = ${JSON.stringify(topics, null, 1)};
`;

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const topics = buildTopics(fs.readFileSync(GUIDE, 'utf8'));
  fs.writeFileSync(OUT, render(topics));
  console.log(`help.js written: ${topics.length} topics`);
}
